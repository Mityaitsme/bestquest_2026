"""Клиент Supabase для серверной стороны (backend)."""

from __future__ import annotations

from supabase import Client, create_client

from config import load_config


def get_supabase_client() -> Client:
    """Создать клиент Supabase (заново на каждый вызов — см. ниже почему).

    Использует service role key, который обходит Row Level Security —
    этот клиент предназначен только для backend и не должен передаваться
    во фронтенд (там будет отдельный клиент на anon key, см. следующие этапы).

    ВАЖНО: раньше клиент кэшировался (@lru_cache) на весь процесс — это и
    было причиной давней перемежающейся ошибки "то не грузится, то грузится"
    (httpx.ReadError [WinError 10054] "удалённый хост разорвал соединение"),
    которая тянулась с ранних этапов проекта и так и не была объяснена.
    Подтверждено экспериментально: на одном и том же долгоживущем процессе
    первый запрос после паузы в несколько минут — почти всегда падает,
    а следующие сразу за ним подряд — все успешны. Это классическое протухание
    держащегося в пуле keep-alive TCP-соединения: httpx считает его ещё
    годным, Supabase уже закрыл его на своей стороне. supabase-py не даёт
    чистого способа подключить ретрай на уровне транспорта (postgrest/storage
    создаются библиотекой сами, без возможности передать свой httpx.Client с
    retries). Пересоздание клиента на каждый вызов исключает саму возможность
    переиспользовать протухшее соединение ценой одного лишнего TCP/TLS-
    рукопожатия на вызов — для нагрузки этого проекта это несущественно.
    """
    config = load_config()
    return create_client(config.supabase_url, config.supabase_service_key)
