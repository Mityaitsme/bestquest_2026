-- На узле с requires_all_options реплика персонажа при ПОСЛЕДНЕМ (закрывающем
-- набор) выборе команды не привязана к конкретному варианту — её получает
-- тот вариант, который команда выбрала последним, кем бы он ни был. Раньше
-- reply_message варианта использовался всегда; теперь узел может задать
-- final_reply, которая подменяет reply_message ИМЕННО у выбора, закрывшего
-- набор (см. backend/dialogue.py: choose_option). Если final_reply не задан,
-- поведение как раньше — используется reply_message выбранного варианта.
alter table dialogue_nodes add column final_reply text;
